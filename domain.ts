// Normalized domain types. Mapped from ConductorOne API responses.

export type CampaignType =
  | "access_certification"
  | "role_review"
  | "separation_of_duties"
  | "other";

export type CampaignStatus = "open" | "closed" | "draft" | "archived";

export interface Campaign {
  id: string;
  name: string;
  description?: string;
  type: CampaignType;
  rawType?: string; // original value from C1 for diagnostics
  status: CampaignStatus;
  startDate?: string; // ISO
  endDate?: string; // ISO (deadline)
  createdAt?: string;
  updatedAt?: string;
  reviewerIds: string[];
  totalReviews: number;
  completedReviews: number;
  percentComplete: number; // 0-100
}

export interface Reviewer {
  id: string; // C1 user id
  email: string;
  displayName: string;
  // Populated from Graph when available
  azureObjectId?: string;
  managerEmail?: string;
  slackUserId?: string;
}

export interface Review {
  id: string;
  campaignId: string;
  reviewerId: string;
  subjectUserId?: string; // whose access is being reviewed
  subjectUserEmail?: string;
  subjectUserDisplayName?: string;
  entitlement?: string;
  status: "pending" | "approved" | "revoked" | "skipped";
  decidedAt?: string;
}

export interface CampaignSnapshot {
  fetchedAt: string;
  campaigns: Campaign[];
  reviewers: Reviewer[];
  reviews: Review[];
}

// EA <-> Exec mapping (many-to-many), admin-managed.
export interface EaMapping {
  eaEmail: string;
  execEmail: string;
  createdAt: string;
  createdBy: string; // admin email
}

export interface NotificationRecord {
  id: string; // uuid
  sentAt: string;
  channel: "slack" | "email" | "slack-channel" | "slack-dm";
  kind:
    | "reminder"
    | "manager_escalation"
    | "skip_level_escalation"
    | "admin_digest"
    | "campaign_open"
    | "overdue_final"
    | "manual"
    | "completion_alert"
    | "account_action";
  recipientEmail: string;
  campaignId?: string;
  success: boolean;
  error?: string;
  // Captured copy of what was actually sent, so admins can review the message
  // in the notification log without rebuilding it from templates.
  subject?: string;
  body?: string;
  // True when this entry was generated by a dry-run send (no Slack/SMTP call).
  dryRun?: boolean;
  // Slack message timestamp — stored so batch re-enable can chat.update the
  // original disable message rather than posting a new one.
  slackTs?: string;
  slackChannel?: string;
  // The actual Slack channel ID (C01234ABC) returned by chat.postMessage.
  // Required for chat.update — channel names don't work reliably there.
  slackChannelId?: string;
  // Emails included in this batch — used when updating the original message.
  batchEmails?: string[];
}

export interface AuditEvent {
  at: string;
  actor: string; // email or "system"
  action: string; // e.g. "notify", "refresh", "ea_mapping.add", "ea_mapping.remove"
  target?: string;
  details?: Record<string, unknown>;
}

export interface AppSettings {
  defaultRules: {
    reminderCron: string;
    managerEscalationDaysBeforeDeadline: number;
    managerEscalationMinIncompletePct: number;
    skipLevelDaysBeforeDeadline: number;
  };
  campaignOverrides: Record<
    string,
    Partial<AppSettings["defaultRules"]> & { disabled?: boolean }
  >;
}

// v2: escalation & notifications configuration.
export type NotificationAudience =
  | "reviewer"
  | "manager" // direct manager (1 level up)
  | "skip" // skip-level (2 levels up)
  | "skip_plus_one" // 3 levels up
  | "chain_to_ceo" // every level above the reviewer up to (and including) CEO's direct reports; plus CEO if the reviewer reports directly to CEO
  | "admin";

export interface EscalationTier {
  id: string;
  name: string;
  // Threshold in days until deadline. A tier is active when daysUntilDeadline is <= this number.
  // Use negative numbers for overdue (e.g. -1 means 1 day overdue or worse).
  daysUntilDeadlineAtMost: number;
  // Default frequency while this tier is active.
  frequency: "weekly" | "daily";
  audiences: NotificationAudience[];
}

export interface TierConfig {
  tiers: EscalationTier[];
}

export interface OrgTopConfig {
  ceoEmail: string;
  // When true, escalation stops at the level just below the CEO (CEO is excluded from copies).
  excludeCeoFromEscalation: boolean;
}

export interface DigestTiming {
  cron: string; // default "0 9 * * 1-5"
  tz: string; // default "America/New_York"
  skipWeekends: boolean;
}

export interface Suppression {
  email: string;
  untilDate: string; // ISO date
  reason?: string;
  createdBy: string;
  createdAt: string;
}

export interface SuppressionState {
  manual: Suppression[];
  // OOF detections are transient and not persisted.
}

export type TemplateSection =
  | "wrapper"
  | "reviewer_pending"
  | "direct_behind"
  | "skip_behind"
  | "deeper_behind"
  | "admin_digest"
  | "account_disabled"
  | "account_enabled"
  | "reviewer_account_disabled"
  | "manager_account_disabled";

export type TemplateChannel = "email" | "slack";

export interface TemplateDoc {
  section: TemplateSection;
  channel: TemplateChannel;
  subject?: string; // wrapper + admin_digest use this for email
  bodyMarkdown: string;
}

export interface TemplateStore {
  global: Record<string, TemplateDoc>; // key = `${section}:${channel}`
  perCampaign: Record<string, Record<string, TemplateDoc>>; // campaignId -> same map
}

// Org tree snapshot (recomputed per digest run, optionally cached briefly).
export interface OrgUser {
  azureId: string;
  email: string;
  displayName: string;
  accountEnabled: boolean;
  managerEmail?: string;
  directReportEmails: string[];
}

export interface OrgTree {
  fetchedAt: string;
  byEmail: Record<string, OrgUser>;
}

// Historical campaign record (from C1 closed campaigns + ongoing tracking).
export interface HistoricalCampaign {
  id: string;
  name: string;
  type: CampaignType;
  openedAt?: string;
  closedAt?: string;
  deadline?: string;
  totalReviews: number;
  completedReviews: number;
  onTimeReviews: number; // completed before deadline
  reviewerCompletion: Array<{
    email: string;
    assigned: number;
    completed: number;
    onTime: number;
  }>;
}

export interface ScorecardRow {
  managerEmail: string;
  managerName: string;
  campaignsParticipated: number;
  totalAssigned: number;
  totalCompleted: number;
  totalOnTime: number;
  onTimePct: number;
  completedPct: number;
  // Aggregated from their downstream tree.
  teamOnTimePct: number;
  teamCompletedPct: number;
}

export type Role = "admin" | "manager" | "reviewer" | "ea";

export interface SessionUser {
  email: string;
  displayName: string;
  azureObjectId: string;
  roles: Role[];
  // Emails of execs this user supports (EA delegation).
  supportsExecs: string[];
}
